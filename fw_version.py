# PlatformIO pre-build script: stamps the firmware with a running build number.
#
# FW_BUILD is the number of commits on HEAD (git rev-list --count), so it goes
# up by one with every commit on main and can be reproduced from the repo.
# FW_GIT is the short sha plus "-dirty" when built with uncommitted changes,
# which is what tells two builds with the same number apart.
#
# The values go into a generated header rather than global build flags, so a
# new commit only recompiles the files that include it.

import os
import subprocess

Import("env")


def git(*args):
    try:
        return subprocess.check_output(
            ["git"] + list(args), cwd=env.subst("$PROJECT_DIR"), stderr=subprocess.DEVNULL
        ).decode().strip()
    except Exception:
        return None


build = git("rev-list", "--count", "HEAD") or "0"
sha = git("describe", "--always", "--dirty", "--abbrev=7") or "unknown"

header = (
    "// generated by fw_version.py -- do not edit\n"
    "#pragma once\n"
    "#define FW_BUILD %s\n"
    '#define FW_GIT "%s"\n' % (build, sha)
)

path = os.path.join(env.subst("$PROJECT_INCLUDE_DIR"), "fw_version_gen.h")
try:
    with open(path) as f:
        unchanged = f.read() == header
except OSError:
    unchanged = False
if not unchanged:
    with open(path, "w") as f:
        f.write(header)

print("Firmware build %s (%s)" % (build, sha))
